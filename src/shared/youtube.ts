export type YoutubeTranscript = {
  ok: true
  videoId: string
  url: string
  title: string
  author: string
  durationSeconds: number
  language: string
  languageName: string
  autoGenerated: boolean
  text: string
}

export type YoutubeTranscriptError = {
  ok: false
  error: string
  videoId?: string
}

export type YoutubeTranscriptResult = YoutubeTranscript | YoutubeTranscriptError

export function isYoutubeVideoId(value: string): boolean {
  return /^[\w-]{11}$/.test(value)
}

export function parseYoutubeVideoId(input: string): string | null {
  const trimmed = input.trim()
  if (!trimmed) return null
  if (isYoutubeVideoId(trimmed)) return trimmed

  try {
    const url = new URL(trimmed)
    const host = url.hostname.replace(/^www\./, '').toLowerCase()
    if (host === 'youtu.be') {
      const id = url.pathname.split('/').filter(Boolean)[0] ?? ''
      return isYoutubeVideoId(id) ? id : null
    }
    if (
      host === 'youtube.com' ||
      host === 'm.youtube.com' ||
      host === 'music.youtube.com' ||
      host === 'youtube-nocookie.com'
    ) {
      const v = url.searchParams.get('v')
      if (v && isYoutubeVideoId(v)) return v
      const parts = url.pathname.split('/').filter(Boolean)
      if (parts.length >= 2 && ['embed', 'shorts', 'live', 'v'].includes(parts[0]) && isYoutubeVideoId(parts[1])) {
        return parts[1]
      }
    }
  } catch {
    // not a URL
  }

  const match = trimmed.match(/(?:v=|youtu\.be\/|shorts\/|embed\/|live\/)([\w-]{11})/)
  return match ? match[1] : null
}

export function youtubeWatchUrl(videoId: string): string {
  return `https://www.youtube.com/watch?v=${videoId}`
}
